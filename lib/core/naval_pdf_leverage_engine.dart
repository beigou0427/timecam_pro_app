import 'package:flutter/foundation.dart';

enum ReportDossierTheme {
  solarEngineering(
    titleZh: '外勤工程 / 案場巡檢驗收報告書',
    titleEn: 'Field Engineering Inspection Dossier',
  ),
  logisticsDelivery(
    titleZh: '物流配送與現場簽收紀錄總表',
    titleEn: 'Logistics Delivery & Handoff Log',
  ),
  trafficPetition(
    titleZh: '現場影像與 GPS 時序彙整表',
    titleEn: 'Timestamped Field Evidence Summary',
  );

  const ReportDossierTheme({required this.titleZh, required this.titleEn});
  final String titleZh;
  final String titleEn;
  String localizedTitle({required bool isZh}) => isZh ? titleZh : titleEn;
}

@immutable
class DossierEntry {
  const DossierEntry({
    required this.sequenceNo,
    required this.utcPlus8Time,
    required this.address,
    required this.gpsText,
    required this.integritySealCode,
    required this.siteOrPlateNote,
    this.thumbnailBase64,
  });
  final int sequenceNo;
  final String utcPlus8Time;
  final String address;
  final String gpsText;
  final String integritySealCode;
  final String siteOrPlateNote;
  final String? thumbnailBase64;
}

class NavalPdfLeverageEngine {
  const NavalPdfLeverageEngine._();
  static const int maxFreeDossierEntries = 1;

  static String escapeHtml(String raw) {
    return raw
        .replaceAll('&', '&amp;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('"', '&quot;')
        .replaceAll("'", '&#39;');
  }

  static List<DossierEntry> enforceExportLimit({
    required List<DossierEntry> entries,
    required bool isProUnlocked,
  }) {
    if (isProUnlocked || entries.length <= maxFreeDossierEntries) {
      return entries;
    }
    return entries.sublist(0, maxFreeDossierEntries);
  }

  static String buildDossierPaywallPitch({
    required int totalCount,
    required bool isZh,
  }) {
    final int safeCount = totalCount.clamp(1, 9999);
    if (isZh) {
      return '免費版僅可匯出 1 筆試閱報告書；升級 Pro 立即解鎖全部 $safeCount 筆批次驗收總表與專屬企業抬頭。';
    }
    return 'Free tier exports 1 sample entry. Upgrade to Pro to export all $safeCount entries with custom headers.';
  }

  static String renderPrintableA4Html({
    required ReportDossierTheme theme,
    required String companyHeader,
    required List<DossierEntry> entries,
    required bool isProUnlocked,
    required bool isZh,
  }) {
    final List<DossierEntry> activeEntries = enforceExportLimit(
      entries: entries,
      isProUnlocked: isProUnlocked,
    );
    final bool includePhotoCol = activeEntries.any(
      (DossierEntry e) =>
          e.thumbnailBase64 != null && e.thumbnailBase64!.trim().isNotEmpty,
    );
    final String safeHeader = escapeHtml(
      companyHeader.trim().isEmpty
          ? (isZh ? 'TimeCam Pro 時間相機專業存證紀錄' : 'TimeCam Pro Field Inspection Log')
          : companyHeader.trim(),
    );
    final String title = escapeHtml(theme.localizedTitle(isZh: isZh));
    final StringBuffer rows = StringBuffer();
    for (final DossierEntry e in activeEntries) {
      final String sanitizedB64 = (e.thumbnailBase64 ?? '')
          .replaceAll(RegExp(r'[^A-Za-z0-9+/=]'), '');
      final String photoCell = includePhotoCol
          ? (sanitizedB64.isNotEmpty
              ? '<td><img src="data:image/jpeg;base64,$sanitizedB64" '
                  'style="width:156px;height:auto;border-radius:6px;border:1px solid #cbd5e1;" /></td>'
              : '<td><small>—</small></td>')
          : '';
      rows.writeln(
        '<tr><td>${e.sequenceNo}</td>$photoCell<td><strong>${escapeHtml(e.utcPlus8Time)}</strong></td>'
        '<td>${escapeHtml(e.address)}<br><small>${escapeHtml(e.gpsText)}</small></td>'
        '<td>${escapeHtml(e.siteOrPlateNote)}</td>'
        '<td><code>${escapeHtml(e.integritySealCode)}</code></td></tr>',
      );
    }
    final String colNo = isZh ? '編號' : 'No.';
    final String colPhoto = includePhotoCol
        ? '<th>${isZh ? '現場影像' : 'Photo'}</th>'
        : '';
    final String colTime = isZh ? '拍攝時間' : 'Timestamp';
    final String colLoc = isZh ? '現場地點與真實座標' : 'Location & Coordinates';
    final String colNote = isZh ? '項目 / 備註' : 'Subject / Note';
    final String colSeal = isZh ? 'SHA-256 檔案校驗碼' : 'SHA-256 Digest';
    final String signOff = isZh
        ? '複核與簽章：______________________　日期：______________'
        : 'Reviewed By / Signature: ______________________   Date: ______________';
    final String disclaimer = isZh
        ? '本報告由時間相機 Pro 於本機裝置自動產出，紀錄時間、GPS 與檔案雜湊摘自拍攝當下裝置原始狀態。'
        : 'Generated locally by TimeCam Pro. Timestamps, coordinates, and SHA-256 hashes reflect device records at capture.';
    final String watermarkFooter = !isProUnlocked
        ? (isZh
            ? '<p style="margin-top:10px;font-size:11px;color:#64748b;">由 <a href="https://apps.apple.com/app/id6836617853" style="color:#090c12;font-weight:700;text-decoration:none;">時間相機 Pro（App Store 下載）</a> 免費試閱版產出・升級 Pro 解鎖完整多筆批次匯出與專屬公司抬頭</p>'
            : '<p style="margin-top:10px;font-size:11px;color:#64748b;">Generated by <a href="https://apps.apple.com/app/id6836617853" style="color:#090c12;font-weight:700;text-decoration:none;">TimeCam Pro</a> Free Preview • Upgrade to Pro for full batch exports &amp; custom company header</p>')
        : '';

    return '<!DOCTYPE html><html><head><meta charset="utf-8"><style>'
        '@page{size:A4;margin:14mm;}body{font-family:-apple-system,"PingFang TC","Helvetica Neue",sans-serif;color:#111827;line-height:1.45;margin:0;}'
        '.hdr{background:#090c12;color:#f8fafc;border-left:5px solid #f5b73b;padding:16px 20px;border-radius:8px;margin-bottom:16px;}'
        '.hdr h2{margin:0 0 4px;font-size:18px;letter-spacing:-0.2px;}'
        '.hdr .sub{font-size:12.5px;color:#f5b73b;font-weight:600;}'
        'table{width:100%;border-collapse:collapse;margin-top:8px;font-size:12px;}'
        'th,td{border:1px solid #cbd5e1;padding:9px 8px;text-align:left;vertical-align:top;}'
        'th{background:#f1f5f9;color:#0f172a;font-weight:700;font-size:11.5px;}'
        'small{color:#475569;font-size:11px;}'
        'code{background:#f1f5f9;color:#0f172a;padding:2px 6px;border-radius:4px;font-size:10.5px;word-break:break-all;}'
        '.sign{margin-top:26px;padding-top:14px;border-top:1px dashed #cbd5e1;font-size:12.5px;font-weight:600;}'
        '.note{margin-top:8px;font-size:10.5px;color:#64748b;}'
        '</style></head><body>'
        '<div class="hdr"><h2>$title</h2><div class="sub">$safeHeader</div></div>'
        '<table><thead><tr><th>$colNo</th>$colPhoto<th>$colTime</th><th>$colLoc</th><th>$colNote</th><th>$colSeal</th></tr></thead>'
        '<tbody>${rows.toString()}</tbody></table>'
        '<div class="sign">$signOff</div>'
        '<div class="note">$disclaimer</div>'
        '$watermarkFooter</body></html>';
  }
}
